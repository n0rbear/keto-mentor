--
-- Scope: existing global catalog records only, addressed by (source,
-- sourceId) with createdById NULL. Names and aliases only: no nutrition is
-- touched and no Food row is created. Every statement is idempotent and a
-- no-op where the record is absent.
--   * names.hu / names.en are set only where that locale has no name yet;
--     an existing non-empty name is never overwritten.
--   * Aliases are inserted ON CONFLICT DO NOTHING (reviewed_migration
--     provenance, like 20260926130000_hungarian_catalog_names).
--   * Bare words that cover several records (tej/Milch/milk, H-tej, kenyér,
--     krémsajt, ribizli, élesztő, ...) are deliberately written as the SAME
--     reviewed alias on each of those records. Equal top matches are the
--     existing "ambiguous" signal (see generic "sajt"): the user gets a choice
--     of catalog records, never a silent pick, and no external lookup or AI.
--     Qualified phrases (teljes tej, 3,5%-os tej, Vollmilch, whole milk,
--     sovány tej, skim milk, ...) sit on exactly one record.

